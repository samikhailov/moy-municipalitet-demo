export function generateSeed(now = new Date()): Task[] {
  const rnd = mulberry32(2026)
  const pick = <T,>(arr: T[]) => arr[Math.floor(rnd() * arr.length)]
  const curator = USERS.find((u) => u.role === "curator")!
  const manager = USERS.find((u) => u.role === "manager")!
  const at = (daysAgo: number, hour: number) => {
    const d = addDays(now, daysAgo)
    d.setHours(hour, Math.floor(rnd() * 60), 0, 0)
    return d.toISOString()
  }
  const tasks: Task[] = []
  let n = 0
  const add = (p: Omit<Task, "id" | "curatorLogin" | "curatorName">) => {
    n += 1
    tasks.push({ id: `T-${String(n).padStart(4, "0")}`, curatorLogin: curator.login, curatorName: curator.name, ...p })
  }

  for (const m of MORGAUSH) {
    const createdAt = at(m.created, 9 + Math.floor(rnd() * 6))
    const updatedAt = m.status === "assign" ? createdAt : at(Math.min(m.created + 2, 0), 10 + Math.floor(rnd() * 6))
    add({
      title: TEMPLATES[m.t][0],
      description: TEMPLATES[m.t][1],
      attachment: m.attachment ?? null,
      dueDate: toISODate(addDays(now, m.due)),
      municipality: "Моргаушский МО",
      executorName: m.executor ? manager.name : null,
      executorLogin: m.executor ? manager.login : null,
      status: m.status,
      createdAt,
      updatedAt,
      completedAt: m.status === "done" ? updatedAt : null,
    })
  }

  for (const muni of MUNICIPALITIES) {
    if (muni === "Моргаушский МО") continue
    const [a, w, d] = COUNTS[muni]
    const executor = pick(EXECUTOR_POOL)
    const plan: TaskStatus[] = [...Array(a).fill("assign"), ...Array(w).fill("work"), ...Array(d).fill("done")]
    for (const status of plan) {
      const [title, description] = pick(TEMPLATES)
      const createdDays = -Math.floor(1 + rnd() * 27)
      const dueOffset =
        status === "done" ? createdDays + Math.floor(3 + rnd() * 10) : status === "work" ? Math.floor(1 + rnd() * 20) : Math.floor(rnd() * 14)
      const createdAt = at(createdDays, 9 + Math.floor(rnd() * 8))
      const updatedAt = status === "assign" ? createdAt : at(Math.min(createdDays + Math.floor(1 + rnd() * 4), 0), 10 + Math.floor(rnd() * 7))
      add({
        title,
        description,
        attachment: rnd() < 0.2 ? "Приложение_к_поручению.pdf" : null,
        dueDate: toISODate(addDays(now, dueOffset)),
        municipality: muni,
        executorName: status === "assign" ? null : executor,
        executorLogin: null,
        status,
        createdAt,
        updatedAt,
        completedAt: status === "done" ? updatedAt : null,
      })
    }
  }
  return tasks
}
